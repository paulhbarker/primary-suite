#!/usr/bin/env python3
"""Writes the launcher icon as Android vector drawables: four arcade buttons,
in the button box's colours, on Simple Games navy.

    python3 scripts/icon/make_icon.py
    scripts/icon/render.sh      # renders PNGs from these vectors

Coordinates are in the adaptive icon's 108 x 108 viewport; the launcher mask
keeps roughly the central 72, and the buttons stay inside the 66 safe circle.
"""
from pathlib import Path

RES = Path(__file__).resolve().parents[2] / "app/src/main/res/drawable"

NAVY_TOP, NAVY, NAVY_BOTTOM = "#FF4A6A99", "#FF36537E", "#FF22395E"

# Box colours (frontend/src/games/button-debug: green, yellow, white, blue),
# each as (highlight, base, shade).
BUTTONS = [
    ((40.5, 40.5), ("#FF6EE79A", "#FF16A34A", "#FF0B6B30")),  # green, button 1
    ((67.5, 40.5), ("#FFFFF3A3", "#FFFACC15", "#FFB88A06")),  # yellow
    ((40.5, 67.5), ("#FFFFFFFF", "#FFE8EDF3", "#FF9AA6B5")),  # white
    ((67.5, 67.5), ("#FF8DB4FF", "#FF2563EB", "#FF173F9E")),  # blue
]
BEZEL_R, GAP_R, DOME_R = 11.0, 9.6, 8.8


def circle(cx, cy, r):
    return (f"M{cx - r:.2f},{cy:.2f}a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0"
            f"a{r:.2f},{r:.2f} 0 1,0 {-2 * r:.2f},0z")


def ellipse(cx, cy, rx, ry):
    return (f"M{cx - rx:.2f},{cy:.2f}a{rx:.2f},{ry:.2f} 0 1,0 {2 * rx:.2f},0"
            f"a{rx:.2f},{ry:.2f} 0 1,0 {-2 * rx:.2f},0z")


def linear(x1, y1, x2, y2, stops):
    items = "".join(f'<item android:offset="{o}" android:color="{c}"/>' for o, c in stops)
    return (f'<aapt:attr name="android:fillColor"><gradient android:type="linear" '
            f'android:startX="{x1}" android:startY="{y1}" android:endX="{x2}" android:endY="{y2}">'
            f"{items}</gradient></aapt:attr>")


def radial(cx, cy, r, stops):
    items = "".join(f'<item android:offset="{o}" android:color="{c}"/>' for o, c in stops)
    return (f'<aapt:attr name="android:fillColor"><gradient android:type="radial" '
            f'android:centerX="{cx}" android:centerY="{cy}" android:gradientRadius="{r}">'
            f"{items}</gradient></aapt:attr>")


def path(d, fill=None, gradient=None, alpha=None):
    attrs = f'android:pathData="{d}"'
    if fill:
        attrs += f' android:fillColor="{fill}"'
    if alpha is not None:
        attrs += f' android:fillAlpha="{alpha}"'
    return f"<path {attrs}>{gradient}</path>" if gradient else f"<path {attrs}/>"


def vector(body):
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            "<!-- Generated by scripts/icon/make_icon.py. Edit that, not this. -->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    xmlns:aapt="http://schemas.android.com/aapt"\n'
            '    android:width="108dp" android:height="108dp"\n'
            '    android:viewportWidth="108" android:viewportHeight="108">\n'
            + "\n".join("    " + p for p in body) + "\n</vector>\n")


def background():
    return vector([
        path("M0,0h108v108h-108z",
             gradient=linear(54, 0, 54, 108, [(0, NAVY_TOP), (0.55, NAVY), (1, NAVY_BOTTOM)])),
        # A soft glow behind the buttons.
        path("M0,0h108v108h-108z",
             gradient=radial(54, 50, 46, [(0, "#33FFFFFF"), (1, "#00FFFFFF")])),
    ])


def foreground():
    body = []
    for (cx, cy), (hi, base, shade) in BUTTONS:
        body.append(path(circle(cx, cy + 1.8, BEZEL_R + 0.3), fill="#FF000000", alpha="0.35"))  # shadow
        body.append(path(circle(cx, cy, BEZEL_R),
                         gradient=linear(cx, cy - BEZEL_R, cx, cy + BEZEL_R,
                                         [(0, "#FF4B5361"), (1, "#FF16191F")])))           # bezel
        body.append(path(circle(cx, cy, GAP_R), fill="#FF0A0C10"))                          # gap
        body.append(path(circle(cx, cy, DOME_R),
                         gradient=radial(cx - 2.9, cy - 3.2, DOME_R * 1.55,
                                         [(0, hi), (0.45, base), (1, shade)])))           # dome
        body.append(path(ellipse(cx - 1.1, cy - 4.1, 5.0, 2.7),
                         gradient=linear(cx, cy - 6.8, cx, cy - 1.4,
                                         [(0, "#B3FFFFFF"), (1, "#00FFFFFF")])))           # gloss
    return vector(body)


if __name__ == "__main__":
    (RES / "ic_launcher_background.xml").write_text(background())
    (RES / "ic_launcher_foreground.xml").write_text(foreground())
    print("wrote", RES / "ic_launcher_background.xml", RES / "ic_launcher_foreground.xml")
